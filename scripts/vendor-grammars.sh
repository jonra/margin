#!/usr/bin/env bash
# Vendors tree-sitter grammars as local C targets and embeds their highlight
# queries as Swift strings (avoids SwiftPM resource bundles in the .app).
set -euo pipefail
cd "$(dirname "$0")/.."
GRAMMARS=("java:Java:v0.23.5" "python:Python:v0.25.0")
QUERIES=Sources/MarginSyntax/HighlightQueries.swift
echo "// Generated by scripts/vendor-grammars.sh — do not edit." > "$QUERIES"
echo "enum HighlightQueries {" >> "$QUERIES"
for entry in "${GRAMMARS[@]}"; do
  IFS=: read -r name Name tag <<< "$entry"
  tmp=$(mktemp -d)
  git -c advice.detachedHead=false clone -q --depth 1 --branch "$tag" "https://github.com/tree-sitter/tree-sitter-$name" "$tmp"
  dest="Sources/TreeSitter$Name"
  rm -rf "$dest"; mkdir -p "$dest/src" "$dest/include"
  cp "$tmp/src/parser.c" "$dest/src/"
  [ -f "$tmp/src/scanner.c" ] && cp "$tmp/src/scanner.c" "$dest/src/"
  cp -R "$tmp/src/tree_sitter" "$dest/src/"
  cp "$tmp/bindings/swift/TreeSitter$Name/"*.h "$dest/include/"
  cp "$tmp/LICENSE" "$dest/LICENSE"
  { echo "    static let $name = #\"\"\""; cat "$tmp/queries/highlights.scm"; echo "\"\"\"#"; } >> "$QUERIES"
  rm -rf "$tmp"
done
echo "}" >> "$QUERIES"
echo "Vendored: ${GRAMMARS[*]}"
